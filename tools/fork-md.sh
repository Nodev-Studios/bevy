#!/usr/bin/env bash
# Writes FORK.md: what this branch changes relative to the upstream Bevy commit it is built on.
# Rerun it after every merge into the branch: tools/fork-md.sh > FORK.md
set -euo pipefail

# Upstream bevyengine/bevy `main` at "Taffy 16 update (#26647)": the upstream parent of the port merge
# (until 2026-11-26 the base was the 0.20.1 release, a0577b5c6). Move it after every merge of upstream main.
BASE=71df17383f6f51f1123196368161a7d1be5ddf0f
cd "$(git rev-parse --show-toplevel)"

echo "# What this fork changes"
echo
echo "Generated by \`tools/fork-md.sh\`; do not edit by hand."
echo
echo "Base: upstream Bevy \`main\` (\`${BASE:0:9}\`, $(git log -1 --format=%cs "$BASE")). Compared: \`$(git rev-parse --short HEAD)\`."
echo
echo "## Upstream commits carried ahead of the base"
echo
# Backports whose upstream original is not yet in the base (the ones already on the base are left out).
ahead=$(git log --reverse --format='%H' "$BASE..HEAD" --grep='cherry picked from commit' | while read -r c; do
  orig=$(git log -1 --format=%B "$c" | sed -n 's/.*cherry picked from commit \([0-9a-f]*\).*/\1/p' | tail -1)
  if [[ -z $orig ]] || ! git merge-base --is-ancestor "$orig" "$BASE" 2>/dev/null; then
    echo "- $(git log -1 --format=%s "$c")"
  fi
done)
echo "${ahead:-None: every upstream commit the fork backported is in the base.}"
echo
echo "## Upstream files this fork edits"
echo
echo "Files that exist upstream at the base and differ here. Each is a possible conflict when upstream is merged."
echo
git diff --diff-filter=MDR --stat=200 "$BASE" HEAD | sed '$d' | sed 's/^ /- `/; s/ *| */` | /'
echo
echo "## Files this fork adds"
echo
git diff --diff-filter=A --name-only "$BASE" HEAD | sed 's/^/- `/; s/$/`/'
